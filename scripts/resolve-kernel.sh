#!/usr/bin/env bash
# Resolve the newest kernel.org release in a selected maintained track and
# pin its source URL + SHA-256 for the entire build/snapshot chain.
set -euo pipefail

OUT=${1:?usage: resolve-kernel.sh OUTPUT_ENV_FILE}
TRACK=${LFS_KERNEL_TRACK:-stable}

python3 - "$OUT" "$TRACK" <<'PY'
import json
import os
import re
import sys
import urllib.request
from urllib.parse import urljoin, urlparse

out, track = sys.argv[1:3]
if track not in ("stable", "mainline", "longterm"):
    raise SystemExit("LFS_KERNEL_TRACK must be stable, mainline, or longterm")

def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "LFS-CN-kernel-resolver/1.0"})
    with urllib.request.urlopen(req, timeout=30) as response:
        return response.read()

meta_url = "https://www.kernel.org/releases.json"
meta = json.loads(fetch(meta_url))
releases = [r for r in meta.get("releases", []) if r.get("moniker") == track and r.get("source")]
if not releases:
    raise SystemExit(f"kernel.org releases.json contains no source for track {track!r}")
# The feed is ordered newest first; choose the first non-EOL release.
release = next((r for r in releases if not r.get("iseol", False)), None)
if release is None:
    raise SystemExit(f"kernel.org reports no maintained release in track {track!r}")

version = release["version"]
if not re.fullmatch(r"[0-9]+\.[0-9]+(?:\.[0-9]+)?", version):
    raise SystemExit(f"unexpected kernel version format: {version!r}")
source = release["source"]
filename = f"linux-{version}.tar.xz"
if not source.endswith("/" + filename):
    raise SystemExit(f"unexpected source URL for Linux {version}: {source}")
checksum_url = urljoin(source, "sha256sums.asc")
checksums = fetch(checksum_url).decode("ascii", "strict")
patterns = [
    re.compile(r"^([0-9a-fA-F]{64})\s+\*?" + re.escape(filename) + r"\s*$", re.M),
    re.compile(r"^SHA256\s+\(" + re.escape(filename) + r"\)\s*=\s*([0-9a-fA-F]{64})\s*$", re.M),
]
sha256 = next((m.group(1).lower() for p in patterns if (m := p.search(checksums))), None)
if not sha256:
    raise SystemExit(f"kernel.org checksum list did not contain {filename}")

os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
with open(out, "w", encoding="utf-8") as f:
    f.write("# Generated by scripts/resolve-kernel.sh; do not edit by hand.\n")
    f.write(f"export LFS_KERNEL_TRACK={track}\n")
    f.write(f"export LFS_KERNEL_VER={version}\n")
    f.write(f"export LFS_KERNEL_SHA256={sha256}\n")
    f.write(f"export LFS_KERNEL_URL={source}\n")
print(f"Linux {version} ({track}), SHA-256 pinned in {out}")
PY
